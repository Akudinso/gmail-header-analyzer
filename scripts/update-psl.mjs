#!/usr/bin/env node
// Regenerates extension/lib/psl-data.js from the Public Suffix List
// (https://publicsuffix.org). Run occasionally: `npm run update-psl`.
//
// Rules are converted to ASCII (punycode) because hostnames from URLs and
// headers are compared in that form. The ICANN and PRIVATE sections are
// kept apart: ICANN suffixes decide the domain that's registered at a
// registry (what RDAP and VirusTotal know about), PRIVATE ones (github.io,
// blogspot.com, ...) decide who controls a site.

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { domainToASCII } from "node:url";

const SOURCE = "https://raw.githubusercontent.com/publicsuffix/list/main/public_suffix_list.dat";
const out = join(dirname(fileURLToPath(import.meta.url)), "..", "extension", "lib", "psl-data.js");

function toAscii(rule) {
  const prefix = rule.startsWith("!") ? "!" : "";
  const body = prefix ? rule.slice(1) : rule;
  const ascii = body
    .split(".")
    .map((label) => (label === "*" ? "*" : domainToASCII(label) || label))
    .join(".");
  return prefix + ascii.toLowerCase();
}

const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`Download failed: HTTP ${res.status}`);
const text = await res.text();

const sections = { icann: [], private: [] };
let section = null;
for (const raw of text.split("\n")) {
  const line = raw.trim();
  if (line.includes("===BEGIN ICANN DOMAINS===")) section = "icann";
  else if (line.includes("===BEGIN PRIVATE DOMAINS===")) section = "private";
  else if (line.includes("===END")) section = null;
  if (!section || !line || line.startsWith("//")) continue;
  sections[section].push(toAscii(line.split(/\s/)[0]));
}
if (sections.icann.length < 5000) throw new Error("Unexpectedly small ICANN section; aborting.");

const version = /VERSION:\s*(\S+)/.exec(text)?.[1] ?? new Date().toISOString().slice(0, 10);
writeFileSync(
  out,
  `// Generated by scripts/update-psl.mjs from the Public Suffix List (${version}).\n` +
    `// Source: ${SOURCE} — licensed under MPL-2.0. Do not edit by hand.\n` +
    `export const PSL_VERSION = ${JSON.stringify(version)};\n` +
    `export const ICANN_RULES = ${JSON.stringify(sections.icann.join(" "))};\n` +
    `export const PRIVATE_RULES = ${JSON.stringify(sections.private.join(" "))};\n`
);
console.log(`Wrote ${sections.icann.length} ICANN and ${sections.private.length} private rules (${version}).`);
